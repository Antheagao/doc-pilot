# What a document with no currency, or one that is not ISO 4217, is formatted
# and validated with. Two digits is the common case, and the assumption is
# recorded on the CurrencyPrecision so a caller can say so.
DEFAULT_MINOR_UNITS = 2

# Largest magnitude a human correction may carry (exclusive). Far above any
# receipt or invoice, far below where a typo becomes a different number.
MAX_AMOUNT = Decimal(10) ** 12

# Most decimal places a quantity may carry: far finer than any receipt
# (weights and volumes sold by the gram or milliliter) and coarse enough that
# a line's quantity times its unit price stays exact in `Decimal`.
MAX_QUANTITY_DECIMALS = 6

# Longest stretch of a rejected value echoed back in an error message.
_ECHO_LIMIT = 80

# Optional minus, digits, optional fraction. No plus sign, exponent, grouping
# commas, non-ASCII digits, or bare ".5" and "5.": every accepted string means
# exactly one number.
_PLAIN_DECIMAL_RE = re.compile(r"-?\d+(\.\d+)?", re.ASCII)


# One printed number: digit runs joined by single dots or commas (or, after a
# leading separator, just the fraction: "$.50"), and whether a percent sign
# follows. It must not continue a longer number, but may follow leader dots
# ("Total ...... 48.30"). A trailing full stop ("total 5.") and a sign or
# currency mark are not part of it.
_PRINTED_NUMBER_RE = re.compile(
    r"(?<!\d)(?<!\d[.,])(?:(\d+(?:[.,]\d+)*)|[.,](\d+))(\s*%)?", re.ASCII
)
_SEPARATOR_RE = re.compile(r"[.,]")
# A number grouped by spaces (a space, no-break, narrow no-break, or thin space)
# or by an apostrophe (Swiss), with an optional decimal part: "1 234,56",
# "1'234.56".
_GROUP_SEPARATORS = " \u00a0\u202f\u2009'\u2019"
_GROUPED_NUMBER_RE = re.compile(
    rf"(?<!\d)(?<!\d[.,])(\d{{1,3}}(?:[{_GROUP_SEPARATORS}]\d{{3}})+)(?:[.,](\d+))?(?!\d)",
    re.ASCII,
)


class MoneyError(ValueError):
    """A value that is not a plain decimal amount. The message is a full
    sentence that a caller can show to a person unchanged."""


def shown_value(raw: object) -> str:
    """`repr(raw)` for an error message, cut to _ECHO_LIMIT characters with
    an ellipsis so a huge input is not echoed back in full."""
    text = repr(raw)
    return text if len(text) <= _ECHO_LIMIT else f"{text[: _ECHO_LIMIT - 3]}..."


@dataclass(frozen=True)
class CurrencyPrecision:
    """How many decimal places a currency uses. `code` is the normalized
    (upper-case) code, or None when the document stated none; `assumption`
    is None for a known code, else why the default was used."""

    code: str | None
    minor_units: int
    assumption: str | None


def currency_precision(code: str | None) -> CurrencyPrecision:
    """The minor units for a currency code (stripped and upper-cased), or the
    default of two with an assumption saying why when the code is missing or
    is not in the ISO 4217 table."""
    cleaned = code.strip().upper() if isinstance(code, str) else ""
    if not cleaned:
        return CurrencyPrecision(
            None,
            DEFAULT_MINOR_UNITS,
            f"no currency stated; assuming {DEFAULT_MINOR_UNITS} decimal places",
        )
    minor_units = ISO_4217_MINOR_UNITS.get(cleaned)
    if minor_units is None:
        return CurrencyPrecision(
            cleaned,
            DEFAULT_MINOR_UNITS,
            f"{cleaned!r} is not an ISO 4217 currency code; "
            f"assuming {DEFAULT_MINOR_UNITS} decimal places",
        )
    return CurrencyPrecision(cleaned, minor_units, None)


def to_decimal(value: object) -> Decimal:
    """Parse an amount or quantity into a finite `Decimal`, or raise MoneyError.

    int and float go through `Decimal(str(value))`: Python's float repr is the
    shortest string that round-trips, so a document-sized amount such as `0.1`
    becomes exactly `Decimal("0.1")`, where `Decimal(0.1)` would carry the
    binary noise. Strings must be plain (see _PLAIN_DECIMAL_RE) once the ends
    are stripped, so `"1e3"`, `"1,234.50"`, `"$5"`, and `""` are refused
    rather than guessed at. A finite `Decimal` passes through.

    bool, None, NaN, and infinities raise: `True` is an int to Python but
    never an amount, and what null means (absent, zero, unreadable) is the
    caller's call, so None is not silently turned into anything here.
    """
    if isinstance(value, bool):
        raise MoneyError(f"{shown_value(value)} is not an amount.")
    if isinstance(value, Decimal):
        parsed = value
    elif isinstance(value, int):
        parsed = Decimal(value)
    elif isinstance(value, float):
        parsed = Decimal(str(value))
    elif isinstance(value, str):
        text = value.strip()
        if not _PLAIN_DECIMAL_RE.fullmatch(text):
            raise MoneyError(
                f"{shown_value(value)} is not a plain number; use digits with an optional "
                "minus sign and a dot for decimals, such as 45.25 (no commas or spaces)."
            )
        parsed = Decimal(text)
    else:
        raise MoneyError(f"{shown_value(value)} is not an amount.")
    if not parsed.is_finite():
        raise MoneyError(f"{shown_value(value)} is not a finite number.")
    return parsed


def fits_minor_unit(d: Decimal, minor_units: int) -> bool:
    """True when `d` has no non-zero digit beyond `minor_units` decimal
    places (`46.250` fits 2, `46.255` does not). Reads the digits directly:
    quantize and normalize round past the context precision of 28 digits."""
    _, digits, exponent = d.as_tuple()
    extra = -exponent - minor_units
    if extra <= 0:
        return True
    return not any(digits[-extra:])


def to_api_string(d: Decimal, minor_units: int) -> str:
    """The canonical decimal string: padded to `minor_units` places, with
    every digit the value needs beyond that.

    `46.2` becomes `"46.20"` and `46.255` stays `"46.255"` for a two-digit
    currency, because rounding would hide a misread. Zeros beyond the minor
    unit carry nothing and are dropped (`46.250` is `"46.25"`), so equal
    values always print the same. Never exponent notation, and negative zero
    prints as plain zero.
    """
    whole, _, fraction = format(d, "f").partition(".")
    if d == 0:
        whole = "0"
    fraction = fraction.rstrip("0").ljust(minor_units, "0")
    return f"{whole}.{fraction}" if fraction else whole


def to_plain_string(d: Decimal) -> str:
    """A quantity as a string: no exponent, no trailing zeros (`2`, `2.5`),
    and negative zero as `0`."""
    return to_api_string(d, 0)


def _places_rule(minor_units: int, currency: CurrencyPrecision | None) -> str:
    """The clause of a too-many-decimals sentence that says what is allowed,
    naming the currency when it is known."""
    allowed = (
        "no decimal places"
        if minor_units == 0
        else f"at most {minor_units} decimal place{'s' if minor_units != 1 else ''}"
    )
    if currency is None:
        return f"this currency allows {allowed}"
    if currency.assumption is None:
        return f"{currency.code} allows {allowed}"
    if currency.code is None:
        return f"no currency is stated, so amounts allow {allowed}"
    return f"{currency.code!r} is not an ISO 4217 currency, so amounts allow {allowed}"


def parse_amount_input(
    raw: str | float, minor_units: int, currency: CurrencyPrecision | None = None
) -> Decimal:
    """Parse an amount a person typed, or a client sent as a correction.

    Stricter than `to_decimal`: the value must also fit the currency's minor
    unit (a person who types `45.255` for a two-digit currency is shown the
    mistake, not given a rounded guess) and stay under MAX_AMOUNT. Every
    failure is a MoneyError whose message is a sentence fit for a 422;
    passing the document's `currency` makes it name the currency.
    """
    amount = to_decimal(raw)
    if not fits_minor_unit(amount, minor_units):
        raise MoneyError(
            f"{shown_value(raw)} has too many decimal places; "
            f"{_places_rule(minor_units, currency)}."
        )
    if abs(amount) >= MAX_AMOUNT:
        raise MoneyError(
            f"{shown_value(raw)} is too large; amounts must be below {MAX_AMOUNT:,}."
        )
    return amount


def parse_quantity_input(raw: str | float) -> Decimal:
    """Parse a line-item quantity a person typed, or a client sent.

    Like `parse_amount_input` but not tied to a currency: at most
    MAX_QUANTITY_DECIMALS decimal places and under MAX_AMOUNT, so a later
    quantity times unit price cannot be made unbounded. Negative quantities
    are allowed (a return).
    """
    quantity = to_decimal(raw)
    if not fits_minor_unit(quantity, MAX_QUANTITY_DECIMALS):
        raise MoneyError(
            f"{shown_value(raw)} has too many decimal places; "
            f"quantities allow at most {MAX_QUANTITY_DECIMALS}."
        )
    if abs(quantity) >= MAX_AMOUNT:
        raise MoneyError(
            f"{shown_value(raw)} is too large; quantities must be below {MAX_AMOUNT:,}."
        )
    return quantity


def to_label_number(d: Decimal) -> int | float:
    """An eval label's JSON number: an int when `d` is whole, else a float.

    The float is `float(d)`, and `Decimal(str(float(d)))` gives `d` back for
    amounts of up to 15 significant digits, which covers every receipt and
    invoice, so a harvested label reads back as the amount that was reviewed.
    """
    if d == d.to_integral_value():
        return int(d)
    return float(d)


def _is_thousands_grouping(groups: Sequence[str]) -> bool:
    """True when digit groups read as a grouped integer: a first group of one
    to three digits (no leading zero), then groups of three (`1,234,567`) or
    the Indian pattern of twos ending in a three (`12,34,567`)."""
    first, rest = groups[0], groups[1:]
    if not 1 <= len(first) <= 3 or first.startswith("0"):
        return False
    if all(len(group) == 3 for group in rest):
        return True
    return len(rest[-1]) == 3 and all(len(group) == 2 for group in rest[:-1])


def _token_readings(token: str, *, percent: bool, places: int | None) -> list[Decimal]:
    """Every number one printed token can mean; empty when it is none.

    One separator is a decimal point (`8.875`, `27,82`) unless exactly three
    digits follow a one-to-three digit head, where it may equally be a
    thousands separator (`1.234`, `1,234`). Then both readings are returned,
    except that a percentage is never grouped (`8.875%` is not 8875%) and a
    field that allows fewer than three decimal places (`places`) cannot hold
    the decimal one (`1,000` printed for a dollar amount is a thousand, not 1).
    The same separator repeated is thousands grouping (`1.234.567`). Two kinds
    mix as grouping then decimals, the last separator being the decimal point
    (`1,234.56`, `1.234,56`). Anything else (a date such as `12.05.2024`) is not
    an amount."""
    separators = _SEPARATOR_RE.findall(token)
    if not separators:
        return [Decimal(token)]
    groups = _SEPARATOR_RE.split(token)
    if len(set(separators)) == 1:
        if len(separators) > 1:
            return [Decimal("".join(groups))] if _is_thousands_grouping(groups) else []
        decimal = Decimal(f"{groups[0]}.{groups[1]}")
        if len(groups[1]) != 3 or percent or not _is_thousands_grouping(groups):
            return [decimal]
        thousands = Decimal("".join(groups))
        return [decimal, thousands] if places is None or places >= 3 else [thousands]
    decimal_point = separators[-1]
    whole, _, fraction = token.rpartition(decimal_point)
    if decimal_point in whole:
        return []
    whole_groups = _SEPARATOR_RE.split(whole)
    if not _is_thousands_grouping(whole_groups):
        return []
    return [Decimal(f"{''.join(whole_groups)}.{fraction}")]


def printed_amounts(text: str, places: int | None = None) -> tuple[Decimal, ...]:
    """The numbers a piece of printed text shows, as non-negative `Decimal`
    magnitudes, in the order they appear and without repeats.

    Reads EU comma decimals (`1.234,56 EUR`), US thousands separators
    (`$1,234.56`), plain decimals (`8.875%`, `$.50`), and integers
    (`2 x 4.50 = 9.00` gives 2, 4.50, and 9.00). Currency signs and codes, `%`,
    minus signs, parentheses, and leader dots are not part of a number, so
    `-$5.00` and `(5.00)` both give 5.00 and the caller decides what the sign
    meant. A token that could be read two ways gives both readings (`1,234` is
    1234 and 1.234) unless `places`, the decimal places the field being checked
    allows, rules the decimal one out (see `_token_readings`); None keeps both.
    A space or an apostrophe between groups of three digits is read as grouping
    (`1 234,56`, `CHF 1'234.56`) in addition to the pieces on either side of it,
    since a space can also just separate two numbers. No number gives `()`.
    """
    found: list[tuple[int, list[Decimal]]] = []
    for match in _PRINTED_NUMBER_RE.finditer(text):
        if match.group(2) is not None:
            found.append((match.start(), [Decimal(f"0.{match.group(2)}")]))
        else:
            found.append(
                (
                    match.start(),
                    _token_readings(match.group(1), percent=match.group(3) is not None, places=places),
                )
            )
    for match in _GROUPED_NUMBER_RE.finditer(text):
        groups = re.split(rf"[{_GROUP_SEPARATORS}]", match.group(1))
        if _is_thousands_grouping(groups):
            fraction = f".{match.group(2)}" if match.group(2) is not None else ""
            found.append((match.start(), [Decimal("".join(groups) + fraction)]))
    amounts: dict[Decimal, None] = {}
    for _, readings in sorted(found, key=lambda entry: entry[0]):
        for reading in readings:
            amounts.setdefault(reading, None)
    return tuple(amounts)
