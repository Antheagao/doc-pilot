"""Money as `Decimal`: parse at the edge, format to the currency's minor unit.

The model reads amounts off a document; code does every sum, comparison, and
rounding decision, and it does it in `Decimal` so `0.1 + 0.2` is `0.3`. Money
enters as a JSON number (a stored model leaf), as a string (a human
correction), or as nothing, and `to_decimal` is the one door all three go
through. Money leaves as a canonical decimal string (`to_api_string`) or, for
eval labels, as the JSON number the label format wants (`to_label_number`).

Nothing here rounds. A value with more digits than the currency's minor unit
keeps them, so a model misreading `46.255` stays visible instead of becoming
a plausible `46.26`; `fits_minor_unit` is how callers ask.

Amounts as they are printed on a document ("$1,234.56", "1.234,56 EUR") are
read by `printed_amounts`, which the value-quote check (app/quotes.py) uses to
see what number a quote shows.
"""

import re
from collections.abc import Sequence
from dataclasses import dataclass
from decimal import Decimal

